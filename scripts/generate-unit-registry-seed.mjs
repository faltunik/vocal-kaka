#!/usr/bin/env node
/**
 * Generates supabase/migrations/20261003000009_seed_unit_registry.sql from
 * data/units/unitDictionary.json. Run after editing the dictionary:
 *
 *   npm run build:units
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DICT_PATH = path.join(rootDir, 'data', 'units', 'unitDictionary.json');
const OUT_PATH = path.join(rootDir, 'supabase', 'migrations', '20261003000009_seed_unit_registry.sql');

const dictionary = JSON.parse(fs.readFileSync(DICT_PATH, 'utf8'));

const quote = (value) => `'${String(value ?? '').replace(/'/g, "''")}'`;
const textArray = (items) => `array[${(items ?? []).map(quote).join(', ')}]::text[]`;

const rows = dictionary.map(unit => [
    '  (',
    [
        quote(unit.code),
        quote(unit.name),
        quote(unit.vernacularName),
        quote(unit.category),
        quote(unit.baseUnit),
        Number(unit.conversionFactor),
        textArray(unit.aliases),
        unit.isFixed ? 'true' : 'false',
        "'seed'",
    ].join(', '),
    ')',
].join(''));

const sql = `-- M0.9 Seed unit_registry from data/units/unitDictionary.json (${dictionary.length} units)
-- Generated by scripts/generate-unit-registry-seed.mjs — do not edit by hand.

insert into public.unit_registry (code, name, vernacular_name, category, base_unit, conversion_factor, aliases, is_fixed, source)
values
${rows.join(',\n')}
on conflict (code) do update set
  name = excluded.name,
  vernacular_name = excluded.vernacular_name,
  category = excluded.category,
  base_unit = excluded.base_unit,
  conversion_factor = excluded.conversion_factor,
  aliases = excluded.aliases,
  is_fixed = excluded.is_fixed,
  source = 'seed';

notify pgrst, 'reload schema';
`;

fs.writeFileSync(OUT_PATH, sql);
console.log(`[build:units] wrote ${dictionary.length} units to ${path.relative(rootDir, OUT_PATH)}`);
